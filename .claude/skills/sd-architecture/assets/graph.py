def md_cell(s):
    return str(s if s is not None else "").replace("|", "\\|").replace("\n", " ")


def md_table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(md_cell(x) for x in r) + " |")
    return "\n".join(out)


def yes_no(v):
    if v is True:
        return "yes"
    if v is False:
        return "no"
    return ""


def render_architecture_md(a, views):
    els = {e["id"]: e for e in as_list(a.get("elements")) if e.get("id")}
    name = (a.get("project") or {}).get("name", "App")
    out = [GENERATED_NOTE.format(src="architecture.json"), "", f"# Architecture: {name}", ""]
    desc = (a.get("project") or {}).get("description")
    if desc:
        out += [desc, ""]
    out += [
        "Dashed border: open, not decided yet. Red border: conflict between sources. Grey: external system.",
        "",
        "## Elements",
        "",
        md_table(
            ["ID", "Name", "Kind", "Parent", "Platform", "Tech", "Status", "Description", "Source"],
            [
                [f"`{e['id']}`", e.get("name"), e.get("kind"), e.get("parent", ""), e.get("platform", ""), e.get("tech", ""),
                 e.get("status", "given"), e.get("description", ""), e.get("source", "")]
                for e in els.values()
            ],
        ),
        "",
        "## Level 1: context",
        "",
        "```mermaid",
        views["l1"],
        "```",
        "",
    ]
    for v in views["l2"]:
        suffix = f", {v['platform']}" if v.get("platform") else ""
        out += [f"## Level 2: containers of {els[v['system']].get('name')}{suffix}", "", "```mermaid", v["mermaid"], "```", ""]
    for v in views["l3"]:
        out += [f"## Level 3: components of {els[v['container']].get('name')}", "", "```mermaid", v["mermaid"], "```", ""]
    data = as_list(a.get("data"))
    zones = {z.get("id"): z.get("name", z.get("id")) for z in as_list(a.get("zones"))}
    if data or zones:
        rows = []
        for d in data:
            for loc in as_list(d.get("locations")):
                rows.append([d.get("name"), zones.get(loc.get("zone"), loc.get("zone")), yes_no(loc.get("plaintext")),
                             yes_no(loc.get("survivesDeath")), yes_no(loc.get("backgroundAccess")),
                             d.get("status", "given"), loc.get("notes", d.get("source", ""))])
        out += ["## Data and trust zones", "", "Orange: plaintext. Green: encrypted. Dashed arrow: must never cross.", "",
                "```mermaid", views["dataflow"], "```", "",
                md_table(["Data", "Zone", "Plaintext", "Survives process death", "Background access", "Status", "Notes or source"], rows),
                ""]
        names = {d.get("id"): d.get("name", d.get("id")) for d in data}
        crossings = as_list(a.get("crossings"))
        if crossings:
            out += ["### Crossings", "", md_table(
                ["From", "To", "Data", "Allowed", "Rule", "Status", "Source"],
                [[zones.get(c.get("from"), c.get("from")), zones.get(c.get("to"), c.get("to")),
                  ", ".join(names.get(x, x) for x in as_list(c.get("data"))), yes_no(c.get("allowed")),
                  c.get("rule", ""), c.get("status", "given"), c.get("source", "")] for c in crossings]), ""]
    resp = as_list(a.get("responsibilities"))
    if resp:
        out += ["## Responsibilities", "", md_table(
            ["Concern", "Owner", "Status", "Source", "Notes"],
            [[r.get("concern"), r.get("owner"), r.get("status", "given"), r.get("source", ""), r.get("notes", "")] for r in resp]), ""]
    return "\n".join(out).rstrip() + "\n"


def render_graph_md(g, comp, warnings):
    name = (g.get("project") or {}).get("name", "App")
    chunks = comp["chunks"]
    changes = comp["changes"]
    out = [GENERATED_NOTE.format(src="graph.json"), "", f"# Work graph: {name}", ""]
    max_cw = max((c["wave"] for c in chunks), default=0)
    out += [f"{len(chunks)} chunks in {max_cw} waves. {len(changes)} changes planned.", ""]
    if comp["chunkPath"]:
        out += ["**Chunk critical path:** " + " → ".join(f"`{x}`" for x in comp["chunkPath"]), ""]
    out += ["## Chunk waves", "", "Chunks in the same wave can be built in parallel.", "",
            md_table(["Wave", "Chunks"], [[w, ", ".join(f"`{c['id']}` ({c['size']})" for c in chunks if c["wave"] == w)]
                                          for w in range(1, max_cw + 1)]), "",
            "```mermaid", comp["chunkMermaid"], "```", "",
            "## Chunks", "",
            md_table(["Chunk", "Title", "Area", "Kind", "Size", "Wave", "Depends on", "Unlocks", "Changes"],
                     [[f"`{c['id']}`", c.get("title"), c.get("area"), c.get("kind", "capability"), c.get("size"), c["wave"],
                       ", ".join(c.get("dependsOn", [])), ", ".join(c["unlocks"]),
                       len(c["changes"]) or "not sliced"] for c in chunks]), ""]
    if changes:
        max_xw = max(c["wave"] for c in changes)
        out += ["## Change waves", "", "Changes in the same wave can be built in parallel, in separate worktrees.", ""]
        if comp["changePath"]:
            out += ["**Change critical path:** " + " → ".join(f"`{x}`" for x in comp["changePath"]), ""]
        out += [md_table(["Wave", "Changes"], [[w, ", ".join(f"`{c['id']}`" for c in changes if c["wave"] == w)]
                                               for w in range(1, max_xw + 1)]), "",
                "```mermaid", comp["changeMermaid"], "```", "",
                "## Ready now", ""]
        ready = [c for c in changes if c["ready"]]
        if ready:
            out += [f"- `{c['id']}`: {c.get('title', '')} ({c['status']})" for c in ready]
        else:
            out += ["Nothing is ready: every open change waits for a dependency or a conflict."]
        active = [c for c in changes if c["status"] == "proposed"]
        if active:
            out += ["", "## In progress", ""] + [f"- `{c['id']}`: {c.get('title', '')}" for c in active]
        out += ["", "## Changes", "",
                md_table(["Change", "Chunk", "Kind", "Size", "Wave", "Depends on", "Stops", "Blocked by", "Status", "Groups"],
                         [[f"`{c['id']}`", c.get("chunk"), c.get("kind", "vertical"), c.get("size"), c["wave"],
                           ", ".join(c.get("dependsOn", [])), ", ".join(c.get("stops", [])),
                           ", ".join(c.get("blockedBy", [])), c["status"],
                           " → ".join(tg.get("name", "") for tg in c.get("taskGroups", []))] for c in changes]), ""]
    if warnings:
        out += ["## Warnings", ""] + [f"- {w}" for w in warnings] + [""]
    return "\n".join(out).rstrip() + "\n"


def render_html(template, payload):
    blob = json.dumps(payload, ensure_ascii=False, sort_keys=True).replace("</", "<\\/")
    if "/*__DATA__*/null" not in template:
        raise ValueError("viewer.html has no /*__DATA__*/null placeholder")
    return template.replace("/*__DATA__*/null", blob)


