def build(base, repo_root):
    rep = Report()
    a = load_json(os.path.join(base, "architecture.json"), rep)
    g = load_json(os.path.join(base, "graph.json"), rep)
    if rep.errors:
        return rep, None
    els = validate_architecture(a, rep)
    chunk_ids, chunk_deps, change_ids, change_deps, by_chunk = validate_graph(g, set(els), rep)
    if rep.errors:
        return rep, None

    relations = as_list(a.get("relations"))
    l1, l1_ids = view_l1(els, relations)
    systems = [e["id"] for e in els.values() if e.get("kind") == "system"
               and any(x.get("parent") == e["id"] and x.get("kind") in ("container", "store") for x in els.values())]
    l2 = []
    for s in systems:
        platforms = sorted({e["platform"] for e in els.values() if e.get("parent") == s
                            and e.get("kind") in ("container", "store") and e.get("platform")})
        for pf in platforms or [None]:
            m, ids = view_l2(els, relations, s, pf)
            l2.append({"system": s, "platform": pf, "mermaid": m, "elements": ids})
    containers = [e["id"] for e in els.values() if e.get("kind") in ("container", "store")
                  and any(x.get("parent") == e["id"] and x.get("kind") == "component" for x in els.values())]
    l3 = []
    for c in containers:
        m, ids = view_l3(els, relations, c)
        l3.append({"container": c, "mermaid": m, "elements": ids})
    views = {"l1": l1, "l1Elements": l1_ids, "l2": l2, "l3": l3, "dataflow": view_dataflow(a)}

    chunk_wave = compute_waves(chunk_ids, chunk_deps)
    chunk_unlocks = compute_unlocks(chunk_ids, chunk_deps)
    chunks_raw = {c["id"]: c for c in as_list(g.get("chunks")) if c.get("id")}
    chunk_path, _ = critical_path(chunk_ids, chunk_deps, {c: SIZES[chunks_raw[c]["size"]] for c in chunk_ids}, chunk_wave)
    for w in range(1, max(chunk_wave.values(), default=0)):
        in_wave = [c for c in chunk_ids if chunk_wave[c] == w]
        if len(in_wave) == 1 and chunks_raw[in_wave[0]]["size"] == "L":
            rep.warn(f"wave {w} is a single L chunk ('{in_wave[0]}'): a bottleneck, consider splitting it")

    changes_raw = {c["id"]: c for c in as_list(g.get("changes")) if c.get("id")}
    change_wave = compute_waves(change_ids, change_deps)
    change_unlocks = compute_unlocks(change_ids, change_deps)
    change_path, _ = critical_path(change_ids, change_deps, {c: SIZES[changes_raw[c]["size"]] for c in change_ids}, change_wave)

    statuses = {}
    for xid in change_ids:
        ch = changes_raw[xid]
        detected = detect_status(repo_root, xid)
        st = effective_status(ch.get("status"), detected)
        declared = ch.get("status", "planned")
        if detected == "proposed" and declared == "planned":
            rep.warn(f"change '{xid}' is proposed in openspec/ but was never designed: run sd-deep-dive {xid}")
        if detected == "archived" and declared in ("planned", "designed", "proposed"):
            rep.warn(f"change '{xid}' is archived in openspec/ but was never verified: run sd-verify {xid}")
        statuses[xid] = st

    area_ids = [x["id"] for x in as_list(g.get("areas"))]
    chunks_out = []
    for cid in sorted(chunk_ids, key=lambda c: (chunk_wave[c], area_ids.index(chunks_raw[c]["area"]), c)):
        c = dict(chunks_raw[cid])
        c.setdefault("dependsOn", [])
        c.setdefault("kind", "capability")
        c["wave"] = chunk_wave[cid]
        c["unlocks"] = sorted(chunk_unlocks[cid])
        c["critical"] = cid in chunk_path
        c["changes"] = sorted(by_chunk.get(cid, []))
        chunks_out.append(c)
    changes_out = []
    for xid in sorted(change_ids, key=lambda c: (change_wave[c], c)):
        ch = dict(changes_raw[xid])
        for k in ("dependsOn", "usedBy", "stops", "blockedBy", "taskGroups", "requirements"):
            ch.setdefault(k, [])
        ch.setdefault("kind", "vertical")
        ch["status"] = statuses[xid]
        ch["wave"] = change_wave[xid]
        ch["unlocks"] = sorted(change_unlocks[xid])
        ch["critical"] = xid in change_path
        ch["ready"] = (statuses[xid] in ("planned", "designed") and not ch["blockedBy"]
                       and all(statuses[d] in DONE for d in change_deps.get(xid, [])))
        changes_out.append(ch)

    comp = {
        "chunks": chunks_out,
        "changes": changes_out,
        "chunkPath": chunk_path,
        "changePath": change_path,
        "chunkMermaid": view_chunks(g, chunk_wave, chunk_path),
        "changeMermaid": view_changes(changes_out, change_wave, change_path),
    }
    arch_md = render_architecture_md(a, views)
    graph_md = render_graph_md(g, comp, rep.warnings)
    payload = {
        "project": a.get("project") or g.get("project") or {},
        "architecture": a,
        "views": views,
        "areas": as_list(g.get("areas")),
        "chunks": chunks_out,
        "changes": changes_out,
        "chunkPath": chunk_path,
        "changePath": change_path,
        "chunkMermaid": comp["chunkMermaid"],
        "changeMermaid": comp["changeMermaid"],
        "warnings": rep.warnings,
    }
    return rep, {"ARCHITECTURE.md": arch_md, "GRAPH.md": graph_md, "payload": payload, "ready": [c for c in changes_out if c["ready"]]}


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description="Validate the system design model and generate its views.")
    ap.add_argument("--dir", help="the docs/architecture folder (default: the parent of this script's folder)")
    ap.add_argument("--check", action="store_true", help="fail if a generated file is stale")
    ap.add_argument("--ready", action="store_true", help="list the changes that can start now")
    args = ap.parse_args()

    base = os.path.abspath(args.dir) if args.dir else os.path.dirname(here)
    repo_root = os.path.dirname(os.path.dirname(base)) if os.path.basename(os.path.dirname(base)) == "docs" else None
    template_path = os.path.join(here, "viewer.html")
    if args.dir and not os.path.exists(template_path):
        template_path = os.path.join(base, "tools", "viewer.html")

    rep, out = build(base, repo_root)
    for w in rep.warnings:
        print("warning: " + w)
    if rep.errors:
        for e in rep.errors:
            print("error: " + e, file=sys.stderr)
        print(f"\n{len(rep.errors)} error(s). Nothing was generated.", file=sys.stderr)
        sys.exit(2)

    if args.ready:
        ready = out["ready"]
        if not ready:
            print("Nothing is ready: every open change waits for a dependency or a conflict.")
        for c in ready:
            print(f"ready        {c['id']}  wave {c['wave']}  {c['status']}  {c.get('title', '')}")
        for c in out["payload"]["changes"]:
            if c["status"] == "proposed":
                print(f"in progress  {c['id']}  wave {c['wave']}  {c.get('title', '')}")
            elif c.get("blockedBy") and c["status"] not in DONE:
                print(f"blocked      {c['id']}  by {', '.join(c['blockedBy'])}")
        return

    if not os.path.exists(template_path):
        print(f"error: {template_path} is missing", file=sys.stderr)
        sys.exit(2)
    with open(template_path, encoding="utf-8") as f:
        template = f.read()
    files = {
        "ARCHITECTURE.md": out["ARCHITECTURE.md"],
        "GRAPH.md": out["GRAPH.md"],
        "architecture.html": render_html(template, out["payload"]),
    }

    if args.check:
        stale = []
        for name, content in files.items():
            path = os.path.join(base, name)
            current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
            if current != content:
                stale.append(name)
        if stale:
            print("stale: " + ", ".join(stale) + ". Run python3 docs/architecture/tools/graph.py", file=sys.stderr)
            sys.exit(1)
        print("Generated files are current.")
        return

    for name, content in files.items():
        with open(os.path.join(base, name), "w", encoding="utf-8") as f:
            f.write(content)
    chunks = out["payload"]["chunks"]
    changes = out["payload"]["changes"]
    max_cw = max((c["wave"] for c in chunks), default=0)
    print(f"{len(chunks)} chunks in {max_cw} waves, {len(changes)} changes, {len(out['ready'])} ready now.")
    if out["payload"]["chunkPath"]:
        print("Chunk critical path: " + " -> ".join(out["payload"]["chunkPath"]))
    print("Wrote ARCHITECTURE.md, GRAPH.md, architecture.html")


if __name__ == "__main__":
    main()
