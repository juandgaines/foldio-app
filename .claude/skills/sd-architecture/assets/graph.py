#!/usr/bin/env python3
"""Validate the system design model and generate its views.

Reads (in the parent folder of this script, normally docs/architecture/):
  architecture.json   C4 elements, relations, trust zones, data, responsibilities
  graph.json          chunks and changes with their dependencies

Writes:
  ARCHITECTURE.md     element table, Mermaid L1, L2, L3, data flow, responsibilities
  GRAPH.md            chunk waves, change waves, critical paths, ready list, warnings
  architecture.html   one-file viewer (diagrams load Mermaid from a CDN; waves work offline)

Usage:
  python3 graph.py            validate, then regenerate everything
  python3 graph.py --check    validate, and exit 1 if a generated file is stale
  python3 graph.py --ready    list the changes that can start now
  python3 graph.py --dir PATH use another docs/architecture folder

Only the Python standard library is used.
"""

import argparse
import json
import os
import re
import sys

ELEMENT_KINDS = {"person", "system", "external", "container", "store", "component"}
STATUSES = {"given", "open", "conflict"}
OWNERS = {"client", "server", "os", "third-party", "shared"}
SIZES = {"S": 1, "M": 2, "L": 3}
CHUNK_KINDS = {"capability", "foundation"}
CHANGE_KINDS = {"vertical", "foundation"}
CHANGE_STATUS = ["planned", "designed", "proposed", "verified", "archived"]
DONE = {"verified", "archived"}
MAX_PR_LINES = 400
SCENARIOS = (2, 6)
MAX_GROUPS = 6

GENERATED_NOTE = "<!-- Generated by tools/graph.py. Do not edit by hand: change {src} and run the script. -->"


class Report:
    def __init__(self):
        self.errors = []
        self.warnings = []

    def error(self, msg):
        self.errors.append(msg)

    def warn(self, msg):
        self.warnings.append(msg)


# ---------------------------------------------------------------- loading


def load_json(path, rep):
    if not os.path.exists(path):
        rep.error(f"{os.path.basename(path)} is missing")
        return None
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except json.JSONDecodeError as e:
        rep.error(f"{os.path.basename(path)} is not valid JSON: line {e.lineno}, column {e.colno}: {e.msg}")
        return None


def as_list(value):
    return value if isinstance(value, list) else []


# ------------------------------------------------------------- validation


def validate_architecture(a, rep):
    elements = as_list(a.get("elements"))
    by_id = {}
    for i, e in enumerate(elements):
        eid = e.get("id")
        where = f"elements[{i}]"
        if not eid:
            rep.error(f"{where} has no id")
            continue
        if eid in by_id:
            rep.error(f"element id '{eid}' is used twice")
        by_id[eid] = e
        if not e.get("name"):
            rep.error(f"element '{eid}' has no name")
        if e.get("kind") not in ELEMENT_KINDS:
            rep.error(f"element '{eid}' has kind '{e.get('kind')}', expected one of {sorted(ELEMENT_KINDS)}")
        if e.get("status", "given") not in STATUSES:
            rep.error(f"element '{eid}' has status '{e.get('status')}', expected one of {sorted(STATUSES)}")
    for eid, e in by_id.items():
        kind = e.get("kind")
        parent = e.get("parent")
        if kind in ("container", "store"):
            if not parent:
                rep.error(f"{kind} '{eid}' needs a parent system")
            elif parent not in by_id:
                rep.error(f"{kind} '{eid}' has unknown parent '{parent}'")
            elif by_id[parent].get("kind") != "system":
                rep.error(f"{kind} '{eid}' must sit in a system, not in a {by_id[parent].get('kind')}")
        elif kind == "component":
            if not parent:
                rep.error(f"component '{eid}' needs a parent container or store")
            elif parent not in by_id:
                rep.error(f"component '{eid}' has unknown parent '{parent}'")
            elif by_id[parent].get("kind") not in ("container", "store"):
                rep.error(f"component '{eid}' must sit in a container or store, not in a {by_id[parent].get('kind')}")
        elif parent:
            rep.warn(f"{kind} '{eid}' has a parent; only containers, stores and components use one")

    for i, r in enumerate(as_list(a.get("relations"))):
        for end in ("from", "to"):
            if r.get(end) not in by_id:
                rep.error(f"relations[{i}] '{end}' is unknown element '{r.get(end)}'")
        if r.get("from") == r.get("to"):
            rep.warn(f"relations[{i}] points from '{r.get('from')}' to itself")

    zones = {}
    for i, z in enumerate(as_list(a.get("zones"))):
        zid = z.get("id")
        if not zid:
            rep.error(f"zones[{i}] has no id")
            continue
        if zid in zones:
            rep.error(f"zone id '{zid}' is used twice")
        zones[zid] = z

    data = {}
    for i, d in enumerate(as_list(a.get("data"))):
        did = d.get("id")
        if not did:
            rep.error(f"data[{i}] has no id")
            continue
        if did in data:
            rep.error(f"data id '{did}' is used twice")
        data[did] = d
        if d.get("status", "given") not in STATUSES:
            rep.error(f"data '{did}' has status '{d.get('status')}'")
        for j, loc in enumerate(as_list(d.get("locations"))):
            if loc.get("zone") not in zones:
                rep.error(f"data '{did}' locations[{j}] has unknown zone '{loc.get('zone')}'")

    for i, c in enumerate(as_list(a.get("crossings"))):
        for end in ("from", "to"):
            if c.get(end) not in zones:
                rep.error(f"crossings[{i}] '{end}' is unknown zone '{c.get(end)}'")
        for did in as_list(c.get("data")):
            if did not in data:
                rep.error(f"crossings[{i}] names unknown data '{did}'")
        if not isinstance(c.get("allowed"), bool):
            rep.error(f"crossings[{i}] needs allowed: true or false")
        if c.get("status", "given") not in STATUSES:
            rep.error(f"crossings[{i}] has status '{c.get('status')}'")

    for i, r in enumerate(as_list(a.get("responsibilities"))):
        if not r.get("concern"):
            rep.error(f"responsibilities[{i}] has no concern")
        if r.get("owner") not in OWNERS:
            rep.error(f"responsibilities[{i}] has owner '{r.get('owner')}', expected one of {sorted(OWNERS)}")
        if r.get("status", "given") not in STATUSES:
            rep.error(f"responsibilities[{i}] has status '{r.get('status')}'")

    systems_with_children = {e.get("parent") for e in by_id.values() if e.get("kind") in ("container", "store")}
    for eid, e in by_id.items():
        if e.get("kind") == "system" and eid not in systems_with_children:
            rep.warn(f"system '{eid}' has no containers yet")

    return by_id


def find_cycle(ids, deps):
    state = {}
    stack = []

    def visit(n):
        state[n] = 1
        stack.append(n)
        for d in deps.get(n, []):
            if d not in ids:
                continue
            if state.get(d) == 1:
                return stack[stack.index(d):] + [d]
            if state.get(d) is None:
                found = visit(d)
                if found:
                    return found
        stack.pop()
        state[n] = 2
        return None

    for n in ids:
        if state.get(n) is None:
            found = visit(n)
            if found:
                return found
    return None


def validate_graph(g, element_ids, rep):
    areas = [a.get("id") for a in as_list(g.get("areas"))]
    if len(set(areas)) != len(areas):
        rep.error("an area id is used twice")
    area_set = set(areas)

    chunks = as_list(g.get("chunks"))
    chunk_ids = []
    for i, c in enumerate(chunks):
        cid = c.get("id")
        if not cid:
            rep.error(f"chunks[{i}] has no id")
            continue
        if cid in chunk_ids:
            rep.error(f"chunk id '{cid}' is used twice")
        chunk_ids.append(cid)
        if not re.match(r"^c\d{2}-[a-z0-9-]+$", cid):
            rep.warn(f"chunk id '{cid}' does not follow cNN-<name>")
        if c.get("area") not in area_set:
            rep.error(f"chunk '{cid}' has unknown area '{c.get('area')}'")
        if c.get("size") not in SIZES:
            rep.error(f"chunk '{cid}' has size '{c.get('size')}', expected S, M or L")
        if c.get("kind", "capability") not in CHUNK_KINDS:
            rep.error(f"chunk '{cid}' has kind '{c.get('kind')}', expected capability or foundation")
        for el in as_list(c.get("containers")):
            if el not in element_ids:
                rep.warn(f"chunk '{cid}' names unknown element '{el}'")
    chunk_set = set(chunk_ids)
    chunk_deps = {}
    for c in chunks:
        cid = c.get("id")
        if not cid:
            continue
        deps = as_list(c.get("dependsOn"))
        for d in deps:
            if d not in chunk_set:
                rep.error(f"chunk '{cid}' depends on unknown chunk '{d}'")
            if d == cid:
                rep.error(f"chunk '{cid}' depends on itself")
        chunk_deps[cid] = [d for d in deps if d in chunk_set and d != cid]
    cyc = find_cycle(chunk_ids, chunk_deps)
    if cyc:
        rep.error("chunk dependency cycle: " + " -> ".join(cyc))

    changes = as_list(g.get("changes"))
    change_ids = []
    for i, ch in enumerate(changes):
        xid = ch.get("id")
        if not xid:
            rep.error(f"changes[{i}] has no id")
            continue
        if xid in change_ids:
            rep.error(f"change id '{xid}' is used twice")
        if xid in chunk_set:
            rep.error(f"change id '{xid}' is also a chunk id")
        change_ids.append(xid)
    change_set = set(change_ids)
    change_deps = {}
    by_chunk = {cid: [] for cid in chunk_ids}
    for ch in changes:
        xid = ch.get("id")
        if not xid:
            continue
        chunk = ch.get("chunk")
        if chunk not in chunk_set:
            rep.error(f"change '{xid}' has unknown chunk '{chunk}'")
        else:
            by_chunk[chunk].append(xid)
            prefix = chunk.split("-")[0] + "-"
            if not re.match(r"^" + re.escape(prefix) + r"\d{2}-[a-z0-9-]+$", xid):
                rep.warn(f"change id '{xid}' does not follow {prefix}MM-<name>")
        if ch.get("size") not in SIZES:
            rep.error(f"change '{xid}' has size '{ch.get('size')}', expected S, M or L")
        kind = ch.get("kind", "vertical")
        if kind not in CHANGE_KINDS:
            rep.error(f"change '{xid}' has kind '{kind}', expected vertical or foundation")
        if ch.get("status", "planned") not in CHANGE_STATUS:
            rep.error(f"change '{xid}' has status '{ch.get('status')}', expected one of {CHANGE_STATUS}")
        deps = as_list(ch.get("dependsOn"))
        for d in deps:
            if d not in change_set:
                rep.error(f"change '{xid}' depends on unknown change '{d}'")
            if d == xid:
                rep.error(f"change '{xid}' depends on itself")
        change_deps[xid] = [d for d in deps if d in change_set and d != xid]

        stops = as_list(ch.get("stops"))
        if len(stops) > 1:
            rep.warn(f"change '{xid}' hits {len(stops)} decision stops ({', '.join(stops)}): split it so each change has at most one")
        scen = ch.get("scenarios")
        if isinstance(scen, int) and not (SCENARIOS[0] <= scen <= SCENARIOS[1]):
            rep.warn(f"change '{xid}' has {scen} scenarios, expected {SCENARIOS[0]} to {SCENARIOS[1]}")
        used_by = as_list(ch.get("usedBy"))
        if kind == "foundation" and not used_by:
            rep.warn(f"foundation change '{xid}' names no change in usedBy")
        for u in used_by:
            if u not in change_set:
                rep.warn(f"change '{xid}' is used by '{u}', which is not planned yet")
        groups = as_list(ch.get("taskGroups"))
        names = [tg.get("name") for tg in groups]
        if len(groups) > MAX_GROUPS:
            rep.warn(f"change '{xid}' has {len(groups)} task groups, more than {MAX_GROUPS}: split the change")
        if groups and kind == "vertical" and not str(names[0]).lower().startswith("domain"):
            rep.warn(f"change '{xid}' starts with task group '{names[0]}', expected Domain first")
        for tg in groups:
            nm = tg.get("name")
            if not nm:
                rep.error(f"change '{xid}' has a task group without a name")
            lines = tg.get("estimateLines")
            if isinstance(lines, int) and lines > MAX_PR_LINES:
                rep.warn(f"change '{xid}' group '{nm}' is estimated at {lines} lines, over {MAX_PR_LINES}: split it")
            if not as_list(tg.get("paths")):
                rep.warn(f"change '{xid}' group '{nm}' lists no paths")
            for a in as_list(tg.get("after")):
                if a not in names:
                    rep.error(f"change '{xid}' group '{nm}' waits for unknown group '{a}'")
        for q in as_list(ch.get("blockedBy")):
            if not re.match(r"^Q\d+$", str(q)):
                rep.warn(f"change '{xid}' is blocked by '{q}', expected a Q id")
        for d in stops:
            if not re.match(r"^D\d+$", str(d)):
                rep.warn(f"change '{xid}' lists stop '{d}', expected a D id")
    cyc = find_cycle(change_ids, change_deps)
    if cyc:
        rep.error("change dependency cycle: " + " -> ".join(cyc))

    change_chunk = {ch.get("id"): ch.get("chunk") for ch in changes if ch.get("id")}
    for cid in chunk_ids:
        if not by_chunk[cid]:
            continue
        for dep_chunk in chunk_deps.get(cid, []):
            if not by_chunk.get(dep_chunk):
                continue
            linked = any(
                change_chunk.get(d) == dep_chunk
                for x in by_chunk[cid]
                for d in change_deps.get(x, [])
            )
            if not linked:
                rep.warn(
                    f"chunk '{cid}' depends on '{dep_chunk}', but none of its changes depends on a change of '{dep_chunk}'"
                )

    return chunk_ids, chunk_deps, change_ids, change_deps, by_chunk


# ------------------------------------------------------------ computation


def compute_waves(ids, deps):
    wave = {}

    def w(n, seen=()):
        if n in wave:
            return wave[n]
        wave[n] = 1 + max((w(d) for d in deps.get(n, [])), default=0)
        return wave[n]

    for n in ids:
        w(n)
    return wave


def compute_unlocks(ids, deps):
    unlocks = {n: [] for n in ids}
    for n in ids:
        for d in deps.get(n, []):
            unlocks[d].append(n)
    return unlocks


def critical_path(ids, deps, weight, wave):
    best = {}
    prev = {}
    for n in sorted(ids, key=lambda x: wave[x]):
        options = [(best[d], d) for d in deps.get(n, []) if d in best]
        if options:
            score, p = max(options)
            best[n] = score + weight[n]
            prev[n] = p
        else:
            best[n] = weight[n]
            prev[n] = None
    if not best:
        return [], 0
    end = max(best, key=lambda n: (best[n], -wave[n]))
    path = []
    n = end
    while n is not None:
        path.append(n)
        n = prev[n]
    return list(reversed(path)), best[end]


def detect_status(repo_root, change_id):
    if not repo_root:
        return None
    base = os.path.join(repo_root, "openspec", "changes")
    archive = os.path.join(base, "archive")
    if os.path.isdir(archive):
        for name in os.listdir(archive):
            if name == change_id or name.endswith("-" + change_id):
                return "archived"
    if os.path.isdir(os.path.join(base, change_id)):
        return "proposed"
    return None


def effective_status(declared, detected):
    declared = declared or "planned"
    if detected and CHANGE_STATUS.index(detected) > CHANGE_STATUS.index(declared):
        return detected
    return declared


# ---------------------------------------------------------------- mermaid


def mid(raw):
    return "n_" + re.sub(r"[^A-Za-z0-9_]", "_", raw)


def mtext(s):
    s = str(s or "")
    return s.replace("&", "#amp;").replace('"', "#quot;").replace("<", "#lt;").replace(">", "#gt;")


def shorten(s, n=60):
    s = " ".join(str(s or "").split())
    if len(s) <= n:
        return s
    cut = s[:n].rsplit(" ", 1)[0]
    return cut + "..."


def label_lines(*parts):
    return "<br/>".join(mtext(p) for p in parts if p)


CLASSDEFS = [
    "classDef ext fill:#f2f2f2,stroke:#888,color:#222",
    "classDef open stroke-dasharray: 5 5",
    "classDef conflict stroke:#c0392b,stroke-width:2px",
    "classDef extopen fill:#f2f2f2,stroke:#888,color:#222,stroke-dasharray: 5 5",
    "classDef extconflict fill:#f2f2f2,stroke:#c0392b,stroke-width:2px,color:#222",
]


def node_class(e):
    status = e.get("status", "given")
    ext = e.get("kind") == "external"
    if status == "open":
        return "extopen" if ext else "open"
    if status == "conflict":
        return "extconflict" if ext else "conflict"
    return "ext" if ext else None


def node_decl(e, detail):
    kind = e.get("kind")
    if detail == "l1":
        text = label_lines(e.get("name"), shorten(e.get("description"), 48))
    elif detail == "l2":
        tech = f"[{e.get('tech')}]" if e.get("tech") else ""
        text = label_lines(e.get("name"), tech)
    else:
        text = label_lines(e.get("name"), shorten(e.get("description"), 40))
    i = mid(e["id"])
    if kind == "person":
        decl = f'{i}(["{text}"])'
    elif kind == "store":
        decl = f'{i}[("{text}")]'
    else:
        decl = f'{i}["{text}"]'
    cls = node_class(e)
    return decl + (f":::{cls}" if cls else "")


def lifted_edges(relations, rep_fn, keep):
    merged = {}
    order = []
    for r in relations:
        a = rep_fn(r.get("from"))
        b = rep_fn(r.get("to"))
        if a is None or b is None or a == b:
            continue
        if not keep(a, b):
            continue
        key = (a, b)
        lbl = r.get("label") or ""
        if r.get("tech"):
            lbl = f"{lbl} [{r['tech']}]" if lbl else f"[{r['tech']}]"
        if key not in merged:
            merged[key] = []
            order.append(key)
        if lbl and lbl not in merged[key]:
            merged[key].append(lbl)
    return [(a, b, "; ".join(merged[(a, b)])) for a, b in order]


def edge_line(a, b, label, dashed=False):
    if label:
        lbl = mtext(shorten(label, 70))
        return f'  {mid(a)} -. "{lbl}" .-> {mid(b)}' if dashed else f'  {mid(a)} -- "{lbl}" --> {mid(b)}'
    return f"  {mid(a)} -.-> {mid(b)}" if dashed else f"  {mid(a)} --> {mid(b)}"


def view_l1(els, relations):
    def rep_fn(x):
        e = els.get(x)
        if not e:
            return None
        k = e.get("kind")
        if k in ("person", "system", "external"):
            return x
        if k in ("container", "store"):
            return e.get("parent")
        if k == "component":
            p = els.get(e.get("parent"), {})
            return p.get("parent")
        return None

    nodes = [e for e in els.values() if e.get("kind") in ("person", "system", "external")]
    edges = lifted_edges(relations, rep_fn, lambda a, b: True)
    lines = ["flowchart LR"]
    for e in nodes:
        lines.append("  " + node_decl(e, "l1"))
    for a, b, lbl in edges:
        lines.append(edge_line(a, b, lbl))
    lines += ["  " + c for c in CLASSDEFS]
    return "\n".join(lines), [e["id"] for e in nodes]


def view_l2(els, relations, system_id, platform=None):
    inside = [e for e in els.values() if e.get("kind") in ("container", "store") and e.get("parent") == system_id
              and (platform is None or not e.get("platform") or e.get("platform") == platform)]
    inside_ids = {e["id"] for e in inside}
    hidden = {e["id"] for e in els.values() if e.get("kind") in ("container", "store") and e.get("parent") == system_id
              and e["id"] not in inside_ids}

    def rep_fn(x):
        e = els.get(x)
        if not e:
            return None
        k = e.get("kind")
        if k == "component":
            x = e.get("parent")
        if k == "system" and x == system_id:
            return None
        if x in hidden:
            return None
        return x

    edges = lifted_edges(relations, rep_fn, lambda a, b: a in inside_ids or b in inside_ids)
    outside_ids = []
    for a, b, _ in edges:
        for x in (a, b):
            if x not in inside_ids and x not in outside_ids:
                outside_ids.append(x)
    sys_el = els[system_id]
    title = sys_el.get("name") + (f" ({platform})" if platform else "")
    lines = ["flowchart LR"]
    for x in outside_ids:
        if els[x].get("kind") == "person":
            lines.append("  " + node_decl(els[x], "l2"))
    lines.append(f'  subgraph {mid(system_id)}["{mtext(title)}"]')
    for e in inside:
        lines.append("    " + node_decl(e, "l2"))
    lines.append("  end")
    for x in outside_ids:
        if els[x].get("kind") != "person":
            lines.append("  " + node_decl(els[x], "l2"))
    for a, b, lbl in edges:
        lines.append(edge_line(a, b, lbl))
    lines += ["  " + c for c in CLASSDEFS]
    return "\n".join(lines), [e["id"] for e in inside] + outside_ids


def view_l3(els, relations, container_id):
    comps = [e for e in els.values() if e.get("kind") == "component" and e.get("parent") == container_id]
    comp_ids = {e["id"] for e in comps}

    def rep_fn(x):
        e = els.get(x)
        if not e:
            return None
        if e.get("kind") == "component" and e.get("parent") != container_id:
            return e.get("parent")
        return x

    edges = lifted_edges(relations, rep_fn, lambda a, b: a in comp_ids or b in comp_ids)
    outside_ids = []
    for a, b, _ in edges:
        for x in (a, b):
            if x not in comp_ids and x not in outside_ids:
                outside_ids.append(x)
    c_el = els[container_id]
    lines = ["flowchart LR"]
    for x in outside_ids:
        if els[x].get("kind") == "person":
            lines.append("  " + node_decl(els[x], "l3"))
    lines.append(f'  subgraph {mid(container_id)}["{mtext(c_el.get("name"))}"]')
    for e in comps:
        lines.append("    " + node_decl(e, "l3"))
    lines.append("  end")
    for x in outside_ids:
        if els[x].get("kind") != "person":
            lines.append("  " + node_decl(els[x], "l2"))
    for a, b, lbl in edges:
        lines.append(edge_line(a, b, lbl))
    lines += ["  " + c for c in CLASSDEFS]
    return "\n".join(lines), [e["id"] for e in comps] + outside_ids


def view_dataflow(a):
    zones = as_list(a.get("zones"))
    data = as_list(a.get("data"))
    per_zone = {z["id"]: [] for z in zones if z.get("id")}
    for d in data:
        for loc in as_list(d.get("locations")):
            if loc.get("zone") in per_zone:
                per_zone[loc["zone"]].append((d, loc))
    names = {d.get("id"): d.get("name", d.get("id")) for d in data}
    lines = ["flowchart LR"]
    for z in zones:
        zid = z.get("id")
        if not zid:
            continue
        zname = mtext(z.get("name", zid))
        if per_zone[zid]:
            lines.append(f'  subgraph {mid("z_" + zid)}["{zname}"]')
            for d, loc in per_zone[zid]:
                state = "plaintext" if loc.get("plaintext") else "encrypted"
                cls = "plain" if loc.get("plaintext") else "enc"
                if d.get("status") == "open":
                    cls += "open"
                lines.append(f'    {mid("d_" + d["id"] + "_" + zid)}["{label_lines(d.get("name"), state)}"]:::{cls}')
            lines.append("  end")
        else:
            lines.append(f'  {mid("z_" + zid)}["{zname}"]')
    for c in as_list(a.get("crossings")):
        what = ", ".join(names.get(x, x) for x in as_list(c.get("data")))
        if not c.get("allowed"):
            lbl = "never: " + what
            lines.append(edge_line("z_" + c["from"], "z_" + c["to"], lbl, dashed=True))
        else:
            lines.append(edge_line("z_" + c["from"], "z_" + c["to"], what))
    lines += [
        "  classDef plain fill:#fff1e0,stroke:#d35400,color:#222",
        "  classDef enc fill:#e8f4ea,stroke:#2e7d32,color:#222",
        "  classDef plainopen fill:#fff1e0,stroke:#d35400,color:#222,stroke-dasharray: 5 5",
        "  classDef encopen fill:#e8f4ea,stroke:#2e7d32,color:#222,stroke-dasharray: 5 5",
    ]
    return "\n".join(lines)


AREA_COLORS = ["#e3f2fd", "#e8f5e9", "#fff3e0", "#f3e5f5", "#e0f7fa", "#fce4ec", "#f1f8e9", "#ede7f6", "#fffde7"]
STATUS_COLORS = {
    "planned": "#ffffff",
    "designed": "#e3f2fd",
    "proposed": "#fff8e1",
    "verified": "#e8f5e9",
    "archived": "#c8e6c9",
}


def view_chunks(g, wave, crit):
    areas = [a["id"] for a in as_list(g.get("areas"))]
    chunks = [c for c in as_list(g.get("chunks")) if c.get("id") in wave]
    lines = ["flowchart LR"]
    max_w = max(wave.values(), default=0)
    for w in range(1, max_w + 1):
        lines.append(f'  subgraph {mid("wave_" + str(w))}["Wave {w}"]')
        for c in sorted((c for c in chunks if wave[c["id"]] == w), key=lambda c: c["id"]):
            cls = "area" + str(areas.index(c["area"]) % len(AREA_COLORS)) if c.get("area") in areas else None
            text = label_lines(c["id"], c.get("title"), c.get("size"))
            lines.append(f'    {mid(c["id"])}["{text}"]' + (f":::{cls}" if cls else ""))
        lines.append("  end")
    for c in chunks:
        for d in as_list(c.get("dependsOn")):
            if d in wave:
                lines.append(f"  {mid(d)} --> {mid(c['id'])}")
    for i, color in enumerate(AREA_COLORS):
        lines.append(f"  classDef area{i} fill:{color},stroke:#666,color:#222")
    for cid in crit:
        lines.append(f"  style {mid(cid)} stroke:#c0392b,stroke-width:3px")
    return "\n".join(lines)


def view_changes(changes, wave, crit):
    lines = ["flowchart LR"]
    max_w = max(wave.values(), default=0)
    for w in range(1, max_w + 1):
        lines.append(f'  subgraph {mid("cw_" + str(w))}["Wave {w}"]')
        for ch in sorted((c for c in changes if wave[c["id"]] == w), key=lambda c: c["id"]):
            extra = []
            if ch.get("stops"):
                extra.append("stop " + ", ".join(ch["stops"]))
            if ch.get("blockedBy"):
                extra.append("blocked by " + ", ".join(ch["blockedBy"]))
            text = label_lines(ch["id"], ch.get("status"), *extra)
            lines.append(f'    {mid(ch["id"])}["{text}"]:::{ch["status"]}')
        lines.append("  end")
    for ch in changes:
        for d in as_list(ch.get("dependsOn")):
            if d in wave:
                lines.append(f"  {mid(d)} --> {mid(ch['id'])}")
    for st, color in STATUS_COLORS.items():
        lines.append(f"  classDef {st} fill:{color},stroke:#666,color:#222")
    for ch in changes:
        if ch.get("blockedBy"):
            lines.append(f"  style {mid(ch['id'])} stroke:#c0392b,stroke-width:2px,stroke-dasharray: 5 5")
    for cid in crit:
        if not any(c["id"] == cid and c.get("blockedBy") for c in changes):
            lines.append(f"  style {mid(cid)} stroke:#c0392b,stroke-width:3px")
    return "\n".join(lines)


